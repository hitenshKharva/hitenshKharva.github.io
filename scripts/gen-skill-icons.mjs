// Generates src/components/skillIcons.ts from Simple Icons, keeping only the logos
// the skills table uses (importing simple-icons at runtime adds ~37 KB gzip).
// Run: node scripts/gen-skill-icons.mjs
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const slugs = [
  "python", "typescript", "openjdk", "apachespark", "apacheairflow", "apachekafka", "looker", "django",
  "snowflake", "postgresql", "mysql", "apachecassandra", "mongodb", "docker", "githubactions",
];
const bySlug = Object.fromEntries(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const entries = slugs.map((s) => {
  const i = bySlug[s];
  if (!i) throw new Error(`Missing icon: ${s}`);
  return `  ${s}: { title: ${JSON.stringify(i.title)}, path: ${JSON.stringify(i.path)} },`;
});
writeFileSync(
  "src/components/skillIcons.ts",
  `// Generated by scripts/gen-skill-icons.mjs from Simple Icons (CC0). Do not edit by hand.\nexport const skillIcons: Record<string, { title: string; path: string }> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Wrote ${entries.length} icons`);
